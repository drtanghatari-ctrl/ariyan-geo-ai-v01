"""
Build step for the Windows .exe (win-w0). The ARIYAN core is shipped as plain .py
files (the provenance ledger hashes them), so PyInstaller cannot see what they
import. This writes ariyan_win/_core_deps.py: one import line per standard-library
or third-party module the core uses, so PyInstaller bundles all of them.
Run from the windows/ folder:  python tools/gen_core_deps.py
"""
import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CORE = os.path.normpath(os.path.join(HERE, "..", "..", "app", "src", "main", "python"))
OUT = os.path.normpath(os.path.join(HERE, "..", "ariyan_win", "_core_deps.py"))

core = {n[:-3] for n in os.listdir(CORE) if n.endswith(".py")}
deps = set()
for n in sorted(core):
    tree = ast.parse(open(os.path.join(CORE, n + ".py"), encoding="utf-8").read())
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names = [a.name for a in node.names]
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            names = [node.module]
        else:
            continue
        for full in names:
            top = full.split(".")[0]
            if top not in core and top not in ("java", "com", "android"):
                deps.add(full)
import importlib.util


def _available(name):
    try:
        return importlib.util.find_spec(name) is not None
    except (ImportError, ValueError):
        return False


skipped = sorted(d for d in deps if not _available(d))   # optional extras the core guards (e.g. rasterio)
deps = {d for d in deps if d not in skipped}
lines = ['"""Generated by tools/gen_core_deps.py -- do not edit. Lets PyInstaller bundle what the core imports."""',
         "", "", "def _never_called():  # imports are only read by PyInstaller, never run"]
for d in sorted(deps):
    lines.append("    import %s  # noqa: F401" % d)
open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote %s (%d modules) from %d core files; not installed, left out: %s"
      % (OUT, len(deps), len(core), ", ".join(skipped) or "none"))
