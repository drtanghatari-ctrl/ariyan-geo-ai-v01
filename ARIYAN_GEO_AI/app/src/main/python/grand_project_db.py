def initialize_schema(conn: sqlite3.Connection) -> None:
    """Creates all Grand Project tables if they don't already exist.
    Safe to call on every app start -- CREATE TABLE IF NOT EXISTS is a
    no-op once the schema is already present, matching this project's
    existing "resumable, re-runnable" philosophy used throughout
    offline_data_manager.py."""
    with conn:
        for statement in _SCHEMA_STATEMENTS:
            conn.execute(statement)


# =========================== GRAND PROJECT ===========================

def create_grand_project(
    db_root: str,
    name: str,
    scientific_title: str = "",
    description: str = "",
    research_area: Optional[Dict[str, Any]] = None,
    coordinate_ref_sys: str = "",
    project_id: Optional[str] = None,
) -> str:
    """Creates a new Grand Project row. Returns the new project's id.
    `research_area`, if given, is stored as JSON (e.g. a bbox or polygon
    dict) -- this module does not interpret its shape.

    `project_id`, if given, is used as-is instead of generating a new
    random id -- added so get_or_create_default_grand_project() (see
    grand_project_sync.py) can create a row under a FIXED, known id and
    reliably find that same row again on a later app run, rather than
    every restart creating a fresh random-id project. Existing callers
    (there are none yet in Kotlin, but this keeps the function
    backward-compatible on principle) are entirely unaffected -- the
    default (None) preserves the original random-id behavior exactly."""
    conn = get_connection(db_root)
    try:
        initialize_schema(conn)
        project_id = project_id or _new_id()
        now = _now_iso()
        with conn:
            conn.execute(
                """
                INSERT INTO grand_project
                    (id, name, scientific_title, description, created_at,
                     last_modified_at, status, current_phase,
                     research_area_json, coordinate_ref_sys, schema_version)
                VALUES (?, ?, ?, ?, ?, ?, 'DRAFT', 'PHASE_0_QUESTION', ?, ?, 1)
                """,
                (
                    project_id, name, scientific_title, description, now, now,
                    json.dumps(research_area) if research_area is not None else None,
                    coordinate_ref_sys,
                ),
            )
        log_timeline_event(
            db_root, project_id, "GRAND_PROJECT_CREATED",
            related_entity_type="grand_project", related_entity_id=project_id,
            description=f"Grand Project '{name}' created.",
        )
        return project_id
    finally:
        conn.close()


def update_grand_project_status(db_root: str, grand_project_id: str, new_status: str) -> None:
    """Updates a Grand Project's lifecycle status. Every transition is
    also logged to timeline_event -- per the handoff doc's rule that a
    project must never silently transition between states."""
    conn = get_connection(db_root)
    try:
        initialize_schema(conn)
        now = _now_iso()
        with conn:
            conn.execute(
                "UPDATE grand_project SET status = ?, last_modified_at = ? WHERE id = ?",
                (new_status, now, grand_project_id),
            )
        log_timeline_event(
            db_root, grand_project_id, "STATUS_CHANGED",
            related_entity_type="grand_project", related_entity_id=grand_project_id,
            description=f"Status changed to {new_status}.",
        )
    finally:
        conn.close()


