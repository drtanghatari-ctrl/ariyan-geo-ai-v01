def update_candidate_confidence(
    db_root: str,
    candidate_id: str,
    band: Optional[str],
    numeric_confidence: Optional[float],
) -> None:
    """Updates the candidate row's OWN "current confidence" columns
    (confidence_band/confidence_numeric) -- ADDED for Phase 1 wiring.
    This is deliberately a plain UPDATE, not append-only: the candidate
    row is meant to reflect "what do we currently think," while the
    FULL history of how that number changed over time lives in
    confidence_history (append-only, see record_confidence_history()
    above). Callers doing a real Steward re-evaluation should call
    BOTH functions together -- record_confidence_history() to preserve
    the trail, and this function to keep the candidate's own row
    current -- exactly the same two-tier pattern the Grand Project
    handoff doc itself describes (section 15: "factual memory" vs.
    "current scientific interpretation")."""
    conn = get_connection(db_root)
    try:
        initialize_schema(conn)
        now = _now_iso()
        with conn:
            conn.execute(
                "UPDATE candidate SET confidence_band = ?, confidence_numeric = ?, last_updated_at = ? WHERE id = ?",
                (band, numeric_confidence, now, candidate_id),
            )
    finally:
        conn.close()


