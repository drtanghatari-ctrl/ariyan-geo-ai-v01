"""
grand_project_db.py

Part of ARIYAN GEO AI's GRAND PROJECT FRAMEWORK (Phase 0 -- persistence
foundation).

PURPOSE: gives ARIYAN a real, persistent, append-only scientific record
that survives across app sessions and across individual investigations --
the schema underlying Grand Project / Hypothesis / Investigation /
Candidate / Evidence Link / Confidence History / Timeline Event /
Calibration Version, per the roadmap agreed 2026-09-13. As of 2026-09-16
(Phase 2.5 Item 3), also underlies Historical Finding / Geographic
Suggestion -- see those tables' own section below for why they are
separate from evidence_link/candidate rather than reusing them.

STORAGE LOCATION -- DELIBERATELY NOT RESOLVED HERE. This module never
decides where its database file lives. It accepts `db_root` as a plain
string parameter to every public function, exactly the same convention
offline_data_manager.py already uses for `offline_data_root`. The actual
value the Kotlin side passes in is `ExternalStorageAccess.offlineDataRoot()
.absolutePath` -- the SAME already-proven-writable directory
MainActivity.kt already uses for offline DEM/NDVI data and for
investigation_status.json (see MainActivity.kt's `offlineDataRoot` lazy
val). This module does not import android/Chaquopy-specific path helpers
and does not guess a second path convention -- it simply opens
"<db_root>/grand_project.db" via plain sqlite3, the same way
offline_data_manager.py writes plain files under its own `offline_data_root`.

DESIGN PRINCIPLES (from the roadmap agreed 2026-09-13):
- Hypothesis objects are EXPLICIT and user-stated per project -- never
  auto-generated by ARIYAN itself (user's own decision).
- Append-only where a table represents scientific history:
  confidence_history and timeline_event rows are NEVER updated or
  deleted after being written -- only ever inserted. This matches the
  Grand Project handoff doc's own rule ("never overwrite historical
  scientific states").
- Rejected/contradicted candidates are NEVER deleted -- only their
  `status` column changes; the row itself persists forever.
- calibration_version exists now but is not populated by anything yet --
  reserved for Phase 5 (self-calibration/learning layer), so Phase 0's
  schema does not need a breaking migration when Phase 5 is built.
- sqlite3 is pure Python stdlib -- confirmed zero new Chaquopy
  dependency risk, unlike the rasterio/GDAL situation this project hit
  and worked around elsewhere (dem_source_mobile.py, ascii_grid.py).

WHAT THIS MODULE DELIBERATELY DOES NOT DO YET:
- No Evidence Graph traversal queries (Phase 2 -- built on top of what
  this module stores, not inside this module).
- No provenance/hash verification (Phase 4 / Steward Stage 2).
- No calibration-suggestion logic (Phase 5) -- `calibration_version`
  is just a table today, nothing writes to it.
- evidence_link.evidence_type remains free-text specifically so a
  future "HISTORICAL_ACCOUNT" value can be added later WITHOUT a
  migration, for the genuinely separate future case of tying an
  already-geocoded historical claim back to an EXISTING DEM candidate's
  lat/lon (post-hoc corroboration). That matching/colocation logic does
  not exist yet and is explicitly NOT what historical_finding/
  geographic_suggestion below are for -- see those tables' own
  docstring note for the distinction.

Every public function here opens its own connection (SQLite handles
this cheaply and this app is single-process); nothing holds a
module-level connection open, so there is no risk of a stale/locked
handle surviving across investigations the way a naive singleton could.
"""

from __future__ import annotations

import json
import os
import sqlite3
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

DB_FILENAME = "grand_project.db"


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _new_id() -> str:
    return uuid.uuid4().hex


def _db_path(db_root: str) -> str:
    return os.path.join(db_root, DB_FILENAME)


def get_connection(db_root: str) -> sqlite3.Connection:
    """Opens (creating if necessary) the Grand Project database under
    `db_root` -- the caller-supplied root, expected to be the SAME
    `offlineDataRoot`/`offline_data_root` value already used elsewhere
    in this project (see module docstring). Ensures the directory
    exists first, exactly like offline_data_manager.py's
    os.makedirs(..., exist_ok=True) calls before writing a manifest.
    Row factory is set to sqlite3.Row so callers get dict-like access
    by column name rather than fragile positional tuples.
    """
    os.makedirs(db_root, exist_ok=True)
    conn = sqlite3.connect(_db_path(db_root))
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


