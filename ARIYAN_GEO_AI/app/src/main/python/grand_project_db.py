# =========================== EVIDENCE LINK ===========================

def add_evidence_link(
    db_root: str,
    candidate_id: str,
    evidence_type: str,
    relation: str,
    detail: Optional[Dict[str, Any]] = None,
) -> int:
    """`evidence_type` is deliberately free-text (not an enum/CHECK
    constraint) -- so a future Phase 2.5 value like
    'HISTORICAL_ACCOUNT' can be inserted without a schema migration.
    `relation` is expected to be one of 'supports' / 'contradicts' /
    'neutral', matching the handoff doc's own vocabulary, but is not
    constrained here either, for the same forward-compatibility reason.
    `detail` is stored as-is as JSON -- intended to be the SAME
    `*_evidence_detail` dict this project's existing evidence sources
    (DEM/NDVI/Thermal/Optical/SAR/GPR/ERT/Stability/Temporal Persistence/
    DEM Cross-Check) already produce, reused rather than reshaped."""
    conn = get_connection(db_root)
    try:
        initialize_schema(conn)
        now = _now_iso()
        with conn:
            cursor = conn.execute(
                """
                INSERT INTO evidence_link
                    (candidate_id, evidence_type, relation, detail_json, recorded_at)
                VALUES (?, ?, ?, ?, ?)
                """,
                (candidate_id, evidence_type, relation,
                 json.dumps(detail) if detail is not None else None, now),
            )
            return cursor.lastrowid
    finally:
        conn.close()


# =========================== CONFIDENCE HISTORY ===========================

def record_confidence_history(
    db_root: str,
    candidate_id: str,
    band: Optional[str],
    numeric_confidence: Optional[float],
    reasoning_snapshot: Optional[List[str]] = None,
    triggering_investigation_id: Optional[str] = None,
) -> int:
    """Append-only. NEVER call an UPDATE against this table from
    anywhere else -- every Steward re-evaluation of a candidate gets
    its own new row here, so the full confidence trajectory over time
    (the doc's section 8 example: 41% -> 49% -> 56% -> 44% -> 61%) is
    reconstructable, not just the current value."""
    conn = get_connection(db_root)
    try:
        initialize_schema(conn)
        now = _now_iso()
        with conn:
            cursor = conn.execute(
                """
                INSERT INTO confidence_history
                    (candidate_id, recorded_at, band, numeric_confidence,
                     reasoning_snapshot_json, triggering_investigation_id)
                VALUES (?, ?, ?, ?, ?, ?)
                """,
                (
                    candidate_id, now, band, numeric_confidence,
                    json.dumps(reasoning_snapshot) if reasoning_snapshot is not None else None,
                    triggering_investigation_id,
                ),
            )
            return cursor.lastrowid
    finally:
        conn.close()


def get_confidence_history(db_root: str, candidate_id: str) -> List[Dict[str, Any]]:
    """Returns every confidence_history row for a candidate, oldest
    first -- the raw material for a future confidence-evolution chart."""
    conn = get_connection(db_root)
    try:
        initialize_schema(conn)
        rows = conn.execute(
            "SELECT * FROM confidence_history WHERE candidate_id = ? ORDER BY id ASC",
            (candidate_id,),
        ).fetchall()
        return [dict(r) for r in rows]
    finally:
        conn.close()


